/** 获取某题目的第 4 层概念反思 */
export function getConceptReflection(
  questionId: string,
): ConceptReflection | undefined {
  return CONCEPT_REFLECTIONS.find((c) => c.questionId === questionId);
}

/** 判断某题目是否有第 4 层概念反思 */
export function hasConceptReflection(questionId: string): boolean {
  return CONCEPT_REFLECTIONS.some((c) => c.questionId === questionId);
}
